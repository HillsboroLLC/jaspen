// Compiles the article markdown drafts into a bundled JS module so the article
// body is present at first render (no runtime fetch). This lets the prerenderer
// capture the full article text into the static HTML for crawlers.
//
// Source of truth stays the markdown files in public/article-review-drafts/*.md;
// this script regenerates src/content/generatedArticles.js on prestart/prebuild.
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const frontendDir = resolve(scriptDir, '..');
const sourceDir = join(frontendDir, 'public', 'article-review-drafts');
const outputPath = join(frontendDir, 'src', 'content', 'generatedArticles.js');

const files = (await readdir(sourceDir))
  .filter((name) => name.endsWith('.md') && name.toLowerCase() !== 'readme.md')
  .sort();

const entries = {};
for (const file of files) {
  const slug = file.replace(/\.md$/, '');
  entries[slug] = await readFile(join(sourceDir, file), 'utf8');
}

const banner =
  '// AUTO-GENERATED by scripts/generate-article-content.mjs — do not edit by hand.\n' +
  '// Source: public/article-review-drafts/*.md. Regenerated on prestart/prebuild.\n';
const module = `${banner}export const ARTICLE_MARKDOWN = ${JSON.stringify(entries, null, 2)};\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, module);
console.log(`Generated ${outputPath} with ${Object.keys(entries).length} articles.`);
